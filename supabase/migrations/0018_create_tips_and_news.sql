-- Creates the tips_and_news table for student updates, guidelines, and study tips.

CREATE TABLE IF NOT EXISTS public.tips_and_news (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    category TEXT NOT NULL CHECK (category IN ('news', 'tip')),
    image_url TEXT,
    author TEXT DEFAULT 'MatricMate Team',
    audience TEXT NOT NULL DEFAULT 'both' CHECK (audience IN ('both', 'natural', 'social')),
    is_pinned BOOLEAN NOT NULL DEFAULT false,
    is_published BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now()),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Performance Indexes
CREATE INDEX IF NOT EXISTS idx_tips_and_news_published 
    ON public.tips_and_news (is_published, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_tips_and_news_category 
    ON public.tips_and_news (category);
CREATE INDEX IF NOT EXISTS idx_tips_and_news_audience 
    ON public.tips_and_news (audience);

-- Row Level Security
ALTER TABLE public.tips_and_news ENABLE ROW LEVEL SECURITY;

-- Read policy: Authenticated users can read published items
CREATE POLICY "Allow authenticated read for published tips and news"
    ON public.tips_and_news
    FOR SELECT
    TO authenticated
    USING (is_published = true);

-- Write policy: Admins only
CREATE POLICY "Allow admins full management of tips and news"
    ON public.tips_and_news
    FOR ALL
    TO authenticated
    USING (
        EXISTS (
            SELECT 1 FROM public.users
            WHERE users.id = auth.uid() AND users.role = 'admin'
        )
    );

